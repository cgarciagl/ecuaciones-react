function MoonIcon() {
  return (
    <svg
      width="15"
      height="15"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      <path d="M21 12.79A9 9 0 1 1 11.21 3 7 7 0 0 0 21 12.79z" />
    </svg>
  );
}

export function ThemeToggle() {
  const theme = useStore((s) => s.theme);
  const setTheme = useStore((s) => s.setTheme);
  const isDark = theme === "dark";

  return (
    <button
      type="button"
      onClick={() => setTheme(isDark ? "light" : "dark")}
      aria-label={isDark ? "Cambiar a tema claro" : "Cambiar a tema oscuro"}
      title={isDark ? "Tema claro" : "Tema oscuro"}
      className="flex items-center justify-center min-w-[34px] min-h-[34px] p-0 border border-line rounded-full bg-white/72 text-ink-soft hover:border-moss-500 hover:text-ink cursor-pointer transition-colors dark:bg-[#1a201a]/72 dark:border-line-strong dark:hover:border-ochre-400 dark:hover:text-ochre-300"
    >
      {isDark ? <SunIcon /> : <MoonIcon />}
    </button>
  );
}
